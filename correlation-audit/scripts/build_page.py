def build_flagged():
    body = ['<p class="note">Items that could not be fully resolved from official sources. Each one cites the source it rests on. Nothing here was blanked silently; withheld values are marked on the register.</p>']
    for fid, sev, title, detail, links in FLAGS:
        body.append(f'<div class="flag"><b>{fid} · {sev}: {html.escape(title)}</b><p>{html.escape(detail)}</p>'
                    f'<p class="note">Sources: {" · ".join(links)}</p></div>')
    body.append('<p class="note">Back to the <a href="index.html">register</a>.</p>')
    return page("Flagged for review", "\n".join(body), "flagged.html")


def check_links(pages):
    bad, total = [], 0
    for name, text in pages.items():
        for href in re.findall(r'href="([^"]+)"', text):
            total += 1
            if href.startswith("https://"):
                if not href.startswith(ALLOWED_HOSTS):
                    bad.append((name, href, "host not allowed"))
                continue
            if href.startswith("#"):
                continue
            target = os.path.normpath(os.path.join(BASE, href))  # '../x' resolves to the repo root
            if not os.path.exists(target):
                bad.append((name, href, "local target missing"))
    return total, bad


def main():
    rec = load("recomputed.json")
    checks = load("input-checks.json")
    spot = load("live-spotcheck-2026-11-14.json")
    idx = build_index(rec, checks, spot)
    flg = build_flagged()
    pages = {"index.html": idx, "flagged.html": flg}
    for name, text in pages.items():
        with open(os.path.join(BASE, name), "w", encoding="utf-8") as f:
            f.write(text)
    total, bad = check_links(pages)
    with open(os.path.join(DATA, "link-check.json"), "w", encoding="utf-8") as f:
        json.dump({"links_checked": total, "failures": bad, "hosts_allowed": list(ALLOWED_HOSTS)}, f, indent=1)
    print(f"pages written: index.html, flagged.html; links checked={total}; failures={len(bad)}")
    for b in bad:
        print("  BROKEN", b)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
