def page(title, body, active):
    nav = [("../index.html", "Root dashboard"), ("../origination/correlations.html", "Published correlation register"),
           ("index.html", "Correlation audit"), ("flagged.html", "Flagged for review")]
    links = " ".join(f'<a href="{h}"{" aria-current=page" if h == active else ""}>{t}</a>' for h, t in nav)
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)} · Own8 correlation audit</title><style>{CSS}</style></head><body>
<header><h1>{html.escape(title)}</h1><p>Own8 · independent recomputation of published correlations · data as of 2026-11-14</p></header>
<nav>{links}</nav><main>{body}</main>
<footer>Official NFL data only for the values shown. Derived model-based values are withheld, not estimated. Generated by correlation-audit/scripts/build_page.py.</footer>
</body></html>"""


def build_index(rec, checks, spot):
    rows = rec["rows"]
    n_match = sum(r["status"] == "MATCH" for r in rows)
    n_off = sum(r["id"] in OFFICIAL for r in rows)
    n_der = sum(r["id"] in DERIVED for r in rows)
    body = []
    body.append('<div class="cards">')
    body.append(f'<div class="card"><b>{len(rows)}</b><span>published correlations (C1–C11)</span></div>')
    body.append(f'<div class="card"><b>{n_match}/{len(rows)}</b><span>reproduced from raw captures (r, n, CI, Holm, ICC)</span></div>')
    body.append(f'<div class="card"><b>{n_off}</b><span>official-input values shown</span></div>')
    body.append(f'<div class="card"><b>{n_der}</b><span>model-derived values withheld (F-01)</span></div>')
    body.append(f'<div class="card"><b>{checks["pass"]}/{checks["total"]}</b><span>input integrity checks pass</span></div>')
    body.append(f'<div class="card"><b>{spot["nfl_scores_week9"]["matched"]}/{spot["nfl_scores_week9"]["observed_games"]}</b><span>Week 9 games re-read live on nfl.com</span></div>')
    body.append(f'<div class="card"><b>{spot["ngs_week8"]["matched"]}/{spot["ngs_week8"]["committed_rows"]}</b><span>NGS Week 8 passer rows re-read live</span></div>')
    body.append("</div>")
    body.append('<p class="note">Rule applied: a correlation is shown only when every input is an official NFL capture. '
                'C2–C4 and C10–C11 use the project\'s walk-forward model outputs, so their values are blank here and flagged (see <a href="flagged.html">Flagged for review</a>). '
                'Reproduction status shows whether the stored value can be recomputed from the committed raw inputs; it does not make a derived value official.</p>')
    body.append("<h2>Correlation register</h2>")
    body.append('<table><thead><tr><th>ID</th><th>Pair</th><th>Scope</th><th class="num">n published</th><th class="num">n recomputed</th>'
                '<th class="num">r</th><th class="num">95% CI</th><th class="num">Holm p (9-test family, as published)</th>'
                '<th class="num">Holm p (official 6-test family)</th><th>Input basis</th><th>Reproduction</th><th>Source links</th></tr></thead><tbody>')
    holm_off = rec["holm_official_family"]["p_holm"]
    for r in rows:
        cid = r["id"]
        pub, rec_ = r["published"], r["recomputed"]
        scope = pub["scope"]
        if cid in OFFICIAL:
            r_cell = f'<td class="num">{fmt_r(rec_["value"])}</td>'
            ci = rec_["ci95"]
            ci_cell = f'<td class="num">[{ci[0]:+.2f}, {ci[1]:+.2f}]</td>'
            hp = f'<td class="num">{fmt_p(pub["p_holm"])}</td>'
            ho = f'<td class="num">{fmt_p(holm_off[cid])}</td>'
        elif r["kind"] == "icc":
            r_cell = '<td class="num withheld">withheld (F-01)</td>'
            ci_cell = '<td class="num withheld">withheld (F-01)</td>'
            hp = '<td class="num withheld">withheld (F-01)</td>'
            ho = '<td class="num">—</td>'
        else:
            r_cell = '<td class="num withheld">withheld (F-01)</td>'
            ci_cell = '<td class="num withheld">withheld (F-01)</td>'
            hp = '<td class="num withheld">withheld (F-01)</td>'
            ho = '<td class="num">—</td>'
        ok = r["status"] == "MATCH"
        repro = '<span class="ok">MATCH</span>' if ok else '<span class="warn">MISMATCH</span>'
        body.append(
            f'<tr><td>{cid}</td><td>{html.escape(r["pair"])}</td><td>{html.escape(scope)}</td>'
            f'<td class="num">{pub["n"]}</td><td class="num">{rec_["n"]}</td>{r_cell}{ci_cell}{hp}{ho}'
            f'<td>{basis(cid)}</td><td>{repro}</td><td class="note">{"<br>".join(sources_for(cid))}</td></tr>')
    body.append("</tbody></table>")
    body.append('<p class="note">Holm p (9-test family) is copied from the published register and was reproduced exactly; it includes the withheld derived tests. '
                'Holm p (official 6-test family) is recomputed over C1 and C5–C9 only. Two-sided p uses the Fisher-z approximation; 95% CI is Fisher-z.</p>')
    body.append("<h2>Live re-reads of the raw captures (2026-11-14)</h2>")
    body.append(f'<p class="note">nfl.com Week 9 scores: {spot["nfl_scores_week9"]["matched"]}/{spot["nfl_scores_week9"]["observed_games"]} games match the game log '
                f'(source: {a(spot["nfl_scores_week9"]["source"], "nfl.com/scores/2026/week-9")}). '
                f'NGS Week 8 passing: {spot["ngs_week8"]["matched"]}/{spot["ngs_week8"]["committed_rows"]} committed rows match the rendered table '
                f'(source: {a(spot["ngs_week8"]["source"], "NGS passing REG/8")}). {html.escape(spot["ngs_week8"]["caveat"])}</p>')
    body.append('<p class="note">Method, sources and the recomputation scripts: <a href="' + REPO_BLOB + 'correlation-audit/scripts/recompute_correlations.py">recompute_correlations.py</a>, '
                '<a href="' + REPO_BLOB + 'correlation-audit/data/recomputed.json">recomputed.json</a>, '
                '<a href="' + REPO_BLOB + 'correlation-audit/data/input-checks.json">input-checks.json</a>. The published register is at '
                '<a href="../origination/correlations.html">origination/correlations.html</a> (owned by another session; read-only here).</p>')
    return page("Correlation audit", "\n".join(body), "index.html")


