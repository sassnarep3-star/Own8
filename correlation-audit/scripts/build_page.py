"""Build correlation-audit/index.html and flagged.html from the recomputation outputs (session 5b52ac15).

Reads only: correlation-audit/data/*.json (written by recompute_correlations.py and spotcheck_live.py).
Withholding rule (operator: 'compute correlations only from officially sourced numbers'):
  OFFICIAL inputs (official captures only)  -> C1, C5-C9  : values shown
  DERIVED inputs (model walk-forward output) -> C2-C4, C10-C11 : r / CI / p / ICC WITHHELD (blank), flagged F-01
Every table row carries at least one https://www.nfl.com or https://nextgenstats.nfl.com link.
Exit 1 if the link check fails.
"""
import html, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
