REPO_BLOB = "https://github.com/sassnarep3-star/Own8/blob/main/"
SCORES = "https://www.nfl.com/scores/2026/week-{w}"
NGS = "https://nextgenstats.nfl.com/stats/passing/2026/REG/{w}"
OFFICIAL = {"C1", "C5", "C6", "C7", "C8", "C9"}
DERIVED = {"C2", "C3", "C4", "C10", "C11"}
ALLOWED_HOSTS = ("https://www.nfl.com/", "https://nextgenstats.nfl.com/", REPO_BLOB)


def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as f:
        return json.load(f)


def fmt_r(x):
    return f"{x:+.3f}"


def fmt_p(x):
    if x is None:
        return "—"
    return "&lt;0.0001" if x < 0.0001 else f"{x:.4f}"


def a(url, label):
    return f'<a href="{html.escape(url, quote=True)}">{html.escape(label)}</a>'


def sources_for(cid):
    if cid == "C1":
        return [a(SCORES.format(w=w), f"W{w}") for w in range(1, 10)] + [("nfl.com scores pages, one per week (game totals and scores)")]
    if cid in ("C5", "C6", "C7", "C8"):
        return ["NGS passing: " + " ".join(a(NGS.format(w=w), f"W{w}") for w in (1, 3, 4, 5, 6, 7, 8)),
                "nfl.com scores: " + " ".join(a(SCORES.format(w=w), f"W{w}") for w in range(1, 10))]
    if cid == "C9":
        return ["NGS passing: " + " ".join(a(NGS.format(w=w), f"W{w}") for w in (1, 3, 4, 5, 6, 7, 8)),
                "nfl.com scores: " + " ".join(a(SCORES.format(w=w), f"W{w}") for w in range(1, 10))]
    # derived: official outcomes + repo model file (not an official source)
    return ["official outcomes: " + " ".join(a(SCORES.format(w=w), f"W{w}") for w in range(3, 10)),
            a(REPO_BLOB + "origination/results/walkforward-games-w10.json", "repo: model residual file (not official)")]


def basis(cid):
    if cid in OFFICIAL:
        return '<span class="ok">official</span>'
    return '<span class="warn">derived from project model</span>'


